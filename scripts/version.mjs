// Writes public/js/version.js with when this version was built and from which commit, for the
// footer of the settings sheet. Runs as part of `npm run build` (Cloudflare runs it on every deploy).
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

function commit() {
  // Workers Builds provides the commit being deployed; locally, ask git.
  const fromCi = process.env.WORKERS_CI_COMMIT_SHA;
  if (fromCi) return fromCi.slice(0, 7);
  try {
    return execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return 'dev';
  }
}

const build = { time: new Date().toISOString(), commit: commit() };
writeFileSync(new URL('../public/js/version.js', import.meta.url), `// Generated by scripts/version.mjs, do not edit.\nexport const BUILD = ${JSON.stringify(build)};\n`);
console.log(`version ${build.commit} built ${build.time}`);
